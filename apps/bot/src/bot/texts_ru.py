#: Приёмы пищи так же, как в кабинете: подписи одного и того же дня не должны
#: расходиться между экраном и чатом.
def meal_name(index: object) -> str:
    """Как называется приём пищи в плане дня.

    Номером, а не именем: число приёмов задаёт назначение (до десяти), и
    «завтрак / обед / ужин / перекус» описывали только четырёхразовый день
    (ADR-0029). Имена приёмов сверх четвёртого знает клиника — вопрос 28.

    Значение приходит из ответа API и в подпись кнопки попадает как есть, если
    это не число: показать «Приём ?» честнее, чем скрыть незнакомое.
    """

    return MEAL_NAME.format(index=index) if isinstance(index, int) else str(index)


