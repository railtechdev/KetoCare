import { QueryClient } from "@tanstack/react-query";

/**
 * Клиент запросов приложения — один на весь экран, настройки по умолчанию.
 *
 * **Записи без сети отказывают сразу** (`mutations.networkMode: "always"`,
 * ADR-0034). По умолчанию TanStack Query ставит мутацию без сети на паузу и
 * отправляет её, когда связь вернётся. Без сохранения очереди и без видимого
 * «ждёт отправки» это худший вариант для записи: закрытая вкладка теряет её
 * молча, а после возврата связи запись уходит с экрана, которого уже нет, —
 * без подтверждения, с дублем при повторном нажатии. Отказ сразу человек
 * видит («нет связи») и повторяет сам, когда сможет.
 *
 * Расчёты (проверка, подбор, пересчёт порций) — не записи: они ничего не
 * сохраняют и ждут связи по замыслу, со строкой ожидания на экране. Их режим
 * закреплён явно в самих хуках.
 */
export function createQueryClient(): QueryClient {
  return new QueryClient({
    defaultOptions: {
      queries: {
        // Как в кабинете: клинические данные не должны выглядеть свежее, чем есть.
        staleTime: 30_000,
        retry: 1,
      },
      mutations: {
        networkMode: "always",
      },
    },
  });
}
