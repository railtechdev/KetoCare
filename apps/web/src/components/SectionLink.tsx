import { Link } from "@tanstack/react-router";
import type { ComponentProps, ReactNode } from "react";

type LinkProps = ComponentProps<typeof Link>;

interface Props {
  section: string;
  children: ReactNode;
  className?: string;
  activeProps?: LinkProps["activeProps"];
  /** Вид дневника, который нужно открыть сразу (для быстрых действий главной) */
  diaryKind?: string;
  /** Вкладка, которую нужно открыть сразу (`?tab=`) */
  tab?: string;
  /** Объект, который нужно открыть в новом разделе (`?item=`) */
  item?: string;
  /** Строка поиска для нового раздела (`?q=`) */
  query?: string;
  /**
   * Пациент, чью карту нужно открыть.
   *
   * Обычно ребёнок переносится сам — семья ведёт одного. У врача пациентов
   * много, и очередь внимания на главной ведёт к конкретному: перенести здесь
   * нечего, нужно задать.
   */
  patient?: string;
  /**
   * Всплывающая подсказка. Нужна там, где видимая подпись скрыта: боковая
   * панель между 768 и 1024 px показывает одни значки, и мыши имя раздела
   * сообщает только она (скринридеру его сообщает `sr-only`-подпись).
   */
  title?: string;
  /**
   * Текущий предмет в перечне. Ставится явно, а не выводится из адреса:
   * «активной» роутер считает ссылку по совпадению пути, а перечень предметов
   * весь ведёт на один и тот же путь и различается только параметром.
   */
  current?: boolean;
  /**
   * Считать ссылку открытой только при точном совпадении адреса.
   *
   * По умолчанию роутер считает открытой и ссылку на начало пути: из карты
   * пациента (`/app/patients/<id>/<раздел>`) ссылка на реестр `/app/patients`
   * получала `aria-current="page"` — то есть возврат наверх представлялся
   * скринридеру текущей страницей. Для бокового меню это поведение верное
   * (раздел действительно открыт), для ссылки «наверх» — нет.
   */
  exact?: boolean;
  onClick?: () => void;
}

/**
 * Ссылка на раздел кабинета.
 *
 * Существует ради переноса параметров адреса. Выбранный ребёнок живёт в адресе
 * (`?patient=`), а TanStack Router по умолчанию параметры поиска при переходе не
 * переносит: без этого родитель двоих детей терял выбор на каждом переходе
 * между разделами и снова упирался в «выберите ребёнка».
 *
 * Обычный `Link` использовать не запрещено, но про перенос параметров в нём
 * нужно помнить каждый раз — а забывается это молча, без ошибки сборки.
 */
export function SectionLink({
  section,
  children,
  className,
  activeProps,
  diaryKind,
  tab,
  item,
  query,
  patient,
  title,
  current,
  exact,
  onClick,
}: Props) {
  return (
    <Link
      to="/app/$section"
      params={{ section }}
      // Выбранный ребёнок переносится, состояние другого экрана — нет:
      // вкладка, объект и строка поиска принадлежат тому разделу, из которого
      // уходим, и на новом означали бы уже другое (`?tab=verify` калькулятора
      // приезжал на главную, а `?item=` карточки продукта — куда угодно).
      // Поэтому все они гасятся по умолчанию и задаются явно там, где нужны:
      // справочник открывает калькулятор на своём продукте (`item`), а
      // калькулятор ведёт в справочник со своим запросом (`query`).
      search={(previous) => ({
        ...previous,
        // Вкладка гасится по умолчанию и задаётся явно там, где переход ведёт
        // к конкретному виду: очередь врача открывает карту сразу на том, из-за
        // чего пациент в неё попал, а не на сводке, откуда нужен ещё клик.
        tab,
        kind: diaryKind,
        item,
        q: query,
        patient: patient ?? previous.patient,
      })}
      className={className}
      title={title}
      aria-current={current ? "true" : undefined}
      activeOptions={exact ? { exact: true } : undefined}
      activeProps={activeProps}
      onClick={onClick}
    >
      {children}
    </Link>
  );
}
