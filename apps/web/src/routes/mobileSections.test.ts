import { readFileSync } from "node:fs";
import { join } from "node:path";

import { describe, expect, it } from "vitest";

import { SECTIONS_BY_ROLE } from "../features/auth/roles";

/**
 * Проверка «экраны семьи помещаются в 360 px» живёт в сквозном прогоне и ведёт
 * перечень разделов руками: `apps/e2e` — отдельный пакет, и реестр кабинета он
 * не импортирует (почему — ниже).
 *
 * Ручной список молча расходится с продуктом. Он уже разошёлся: у родителя
 * десять разделов, а проверялись семь — «Помощник», «Ребёнок» и «Профиль» на
 * телефонной ширине не открывал никто, при том что раздел 8.2 ТЗ называет
 * мобильный веб основным каналом семьи. Заметить это мог только человек,
 * сверивший два файла глазами.
 *
 * Поэтому файл прогона читается с диска и сверяется с ролевой таблицей. Тест
 * стоит в кабинете, а не в прогоне: ночной прогон идёт раз в сутки, а этот
 * падает сразу — в той же проверке, что и добавление раздела.
 *
 * Почему не импорт: `apps/e2e` не зависит ни от одного рабочего пакета, и
 * глубокий импорт через границу пакета менял бы это решение ради одной
 * константы. Технически он возможен (`roles.ts` не тянет ничего за собой) —
 * но чтение исходников с диска здесь домашний приём (`layout.test.ts`,
 * `styles.test.ts`, `i18n.test.ts`).
 *
 * Чего этот тест НЕ проверяет: что по списку действительно ходят. Обход
 * `for (const section of SECTIONS)` живёт в прогоне, и `slice`, `continue` или
 * `test.skip` внутри него сторож не увидит. Он отвечает за состав перечня, не
 * за его использование.
 */
const SPEC = join(
  import.meta.dirname,
  "..",
  "..",
  "..",
  "e2e",
  "tests",
  "mobile.spec.ts",
);

function sectionsFromSpec(): string[] {
  // Комментарии вычищаются из ВСЕГО исходника до поиска перечня. Так закрыты
  // сразу два случая: раздел, выключенный ровно тем способом, которым их и
  // выключают (`// временно: "assistant",`), и закрывающая скобка внутри
  // комментария — она обрывала захват, и сообщение объявляло пропавшими
  // нетронутые разделы. Приём тот же, что в `layout.test.ts`.
  const source = readFileSync(SPEC, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\/\/[^\n]*/g, "");

  // Захват привязан к концу объявления, а не к первой скобке: иначе
  // `].slice(0, 7) as const;` — самый тихий способ урезать проверку — проходил
  // бы незамеченным, потому что литерал остался бы полным.
  const list = /const SECTIONS = \[([^\]]*)\] as const;/.exec(source);
  if (list === null) {
    throw new Error(
      `В ${SPEC} не найден перечень вида «const SECTIONS = [...] as const;». ` +
        "Если он переименован или обёрнут вызовом — поправьте и здесь: сторож " +
        "обязан читать ровно тот литерал, по которому идёт обход.",
    );
  }

  // Класс символов широкий: имя раздела — ключ ролевой таблицы, и `careTeam`
  // или `log_2` там законны. С узким `[a-z-]` такой раздел молча выпадал бы из
  // разбора, а сообщение требовало бы добавить уже добавленное.
  return [...list[1]!.matchAll(/"([A-Za-z0-9_-]+)"/g)].map(
    (match) => match[1]!,
  );
}

describe("экраны семьи на телефоне", () => {
  it("проверяются все разделы родителя, а не часть", () => {
    const checked = new Set(sectionsFromSpec());
    const missing = SECTIONS_BY_ROLE.parent.filter(
      (section) => !checked.has(section),
    );

    expect(
      missing,
      `эти разделы родителя не проверяются на 360 px — допишите их в ${SPEC}`,
    ).toEqual([]);
  });

  it("не проверяет разделов, которых у родителя нет", () => {
    // Обратная сторона: раздел, убранный у роли, остался бы в прогоне и
    // открывался бы под родителем — то есть проверка ходила бы туда, куда
    // человек не ходит.
    const known = new Set(SECTIONS_BY_ROLE.parent);
    expect(
      sectionsFromSpec().filter((section) => !known.has(section)),
      `в ${SPEC} перечислены разделы, которых у родителя нет`,
    ).toEqual([]);
  });
});
