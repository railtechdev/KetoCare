/**
 * Первичные действия, видимые на экране.
 *
 * Правило П31 канона задаёт **максимум**: первичное действие экрана одно. Это
 * не требование иметь его на каждом экране — экран, работа на котором идёт
 * правкой на месте (план дня), обходится без него. Требование в другом: пять
 * одинаково громких кнопок подряд не отвечают на вопрос «с чего начать», они
 * его задают.
 *
 * Считаем по акцентному фону, а не по пропу `variant`: у кита первичный вид —
 * умолчание, то есть отсутствие пропа, и статически такие кнопки не отличить
 * от нарисованных в цикле. На отрисованном экране они видны как есть.
 */
export function primaryActions(container: HTMLElement): string[] {
  return [...container.querySelectorAll("button, a")]
    .filter((element) => /(^|\s)bg-primary(\s|$)/.test(element.className))
    .map((element) => element.textContent?.trim() ?? "");
}
