import type { components } from "@ketocare/api-client";

export type DayTolerance = components["schemas"]["DayTolerance"];

export interface DayVerdict {
  /** Кетосоотношение вышло за допуск назначения. */
  ratioOffTolerance: boolean;
  /** Набранная калорийность не дотягивает до суточной нормы назначения. */
  kcalBelowTarget: boolean;
  /** Сравнивать не с чем: активного назначения нет или вердикта в ответе нет. */
  unavailable: boolean;
}

/**
 * Что интерфейс говорит о соответствии дня назначению.
 *
 * Сами допуски — медицинские константы ядра, они считаются на сервере
 * (правило 2 CLAUDE.md), и копии в TypeScript нет. Здесь решается другое: какой
 * из двух вердиктов сервера показывать предупреждением.
 *
 * Кетосоотношение — показывать. Оно обязано держаться в каждом приёме пищи,
 * поэтому его расхождение с назначением верно в любой момент дня.
 *
 * Калорийность — не показывать. Сервер сравнивает набранное за день с СУТОЧНОЙ
 * нормой, а признака «день спланирован до конца» нет ни у сервера, ни у
 * клиента. До последнего запланированного приёма вердикт всегда отрицательный:
 * предупреждение горело бы постоянно и у родителя, и в списке пациентов у
 * врача — и приучило бы не читать предупреждения вообще, включая те, что значат
 * настоящее отклонение от назначения. Поэтому калорийность показывается набором
 * («набрано 401 из 1200»), а не расхождением.
 *
 * Как правильно сравнивать неполный день с суточной нормой — вопрос медицинской
 * команды (docs/medical/OPEN_QUESTIONS.md, вопрос 9). Решение живёт здесь одной
 * функцией: пока оно было размазано по четырём экранам, правка одного из них не
 * доходила до остальных, и один и тот же день описывался по-разному на главной,
 * в меню и в карте пациента.
 */
export function dayVerdict(
  tolerance: DayTolerance | null | undefined,
): DayVerdict {
  if (tolerance === null || tolerance === undefined) {
    return {
      ratioOffTolerance: false,
      kcalBelowTarget: false,
      unavailable: true,
    };
  }

  return {
    ratioOffTolerance: !tolerance.ratio_within_tolerance,
    kcalBelowTarget: !tolerance.kcal_within_tolerance,
    unavailable: false,
  };
}
