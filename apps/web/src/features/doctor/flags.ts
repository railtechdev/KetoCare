import { parseDateInput } from "../diary/time";
import type { PatientOverview } from "./types";

/**
 * Порог флага «нет данных» в сутках.
 *
 * TODO(med): значение не подтверждено медицинской командой. Раздел 8.3 ТЗ задаёт
 * его как «default 3, # TODO(med)», то есть это заглушка до решения врачей, а не
 * обоснованный порог. Живёт одной именованной константой и подставляется в
 * подписи через i18n: число, размазанное по разметке и текстам, обновляют не
 * целиком, и часть экрана продолжила бы жить по старому порогу.
 */
export const NO_DATA_FLAG_DAYS = 3;

/**
 * Порог молчания в первый месяц терапии — строгое наблюдение.
 *
 * Ответ клиники от 09.09.2026 (вопрос 11): «от начала диеты в течение месяца
 * должен идти строгий мониторинг, и здесь даже один день молчания будет
 * звонком». Режим («первый месяц или нет») решает сервер — ему нужна дата
 * начала терапии, а она лежит в медицинском профиле. Порог в днях живёт здесь,
 * рядом с обычным: оба подставляются в легенду пометок.
 *
 * **Почему 2, а не 1.** Счёт тот же, что у обычного порога: календарные сутки
 * от последней записи до сегодня. «Один день молчания» — это целые прошедшие
 * сутки без записей: вчера семья не внесла ничего, последняя запись позавчера,
 * разница 2. С порогом 1 пометка загоралась бы с утра у каждой семьи, которая
 * сегодня ещё не успела записать, — а сегодняшний день ещё идёт, и молчанием
 * его не назовёшь. Флаг, горящий у всего списка, перестаёт что-либо выделять.
 *
 * TODO(med): вопрос 11 — толкование «одного дня» переспрошено.
 */
export const STRICT_NO_DATA_FLAG_DAYS = 2;

export interface PatientFlags {
  /**
   * Активного назначения нет.
   *
   * Ребёнок прикрепляется к врачу в момент, когда семья его заводит, и делает
   * это молча: врач узнавал о новом пациенте, только открыв список и дочитав
   * его до нужной строки. При этом задать назначение — первое, что от врача
   * требуется, и до него не работает ничего остального: сверять день не с чем,
   * калькулятор не знает цели, а вердикт о допуске не существует.
   */
  noPrescription: boolean;
  /**
   * Сутки с последней записи, известной серверу; null — записей ещё не было.
   *
   * Именно «не было», а не «не удалось посчитать»: неразобранная дата сводки
   * отсекается раньше и даёт `null` вместо всего набора флагов.
   */
  daysSinceLastReading: number | null;
  /**
   * Замеров нет дольше порога — или их не было вовсе. Порог зависит от режима
   * наблюдения: `STRICT_NO_DATA_FLAG_DAYS` в первый месяц терапии,
   * `NO_DATA_FLAG_DAYS` после.
   *
   * «Данные» здесь — последний замер кетонов, последний замер веса и записи о
   * приступах за сегодня; их день сервер отдаёт готовым (`last_reading_on`).
   * Полный признак «семья ничего не вносила N дней» по всем шести дневникам
   * сводка не отдаёт — и легенда пометок говорит об этом прямо (вопрос 11).
   */
  staleData: boolean;
  /**
   * Пациент в первом месяце терапии — строгое наблюдение (вопрос 11).
   *
   * Режим приходит от сервера: ему нужна дата начала терапии. Нужен не только
   * для порога, но и строке пациента: пометка в этот месяц загорается раньше
   * обычного, и без пояснения «Нет замеров: 2 дн.» рядом с легендой про трое
   * суток читалось бы как ошибка.
   */
  strictMonitoring: boolean;
  /**
   * Кетосоотношение дня не уложилось в допуски назначения.
   *
   * Вердикт приходит от сервера (`day.tolerance`): допуски — медицинские
   * константы ядра (правило 2 CLAUDE.md), их копия в TypeScript со временем
   * разошлась бы с расчётом, и список показывал бы «в норме» там, где ядро
   * считает иначе.
   *
   * Калорийность в флаг не входит. Сервер сравнивает набранное за день с
   * суточной нормой, поэтому у любого пациента с недоспланированным днём
   * `kcal_within_tolerance` ложен — флаг горел бы у всего списка сразу и
   * перестал бы что-либо выделять. Кетосоотношение таким свойством не обладает:
   * оно обязано держаться в каждом приёме. Как сравнивать неполный день с
   * суточной нормой — вопрос медицинской команды
   * (docs/medical/OPEN_QUESTIONS.md, вопрос 9).
   */
  nutritionOff: boolean;
  /**
   * Суммарное число приступов за неделю выросло больше чем наполовину.
   *
   * Порог и величина — ответ клиники от 09.09.2026 (вопрос 12): «суммарное
   * число приступов (более 50 %)». Считает сервер: это медицинское правило, и
   * его копия в TypeScript однажды разошлась бы с расчётом.
   */
  seizuresGrew: boolean;
  /**
   * Приступы появились после недели без них.
   *
   * Отдельно от роста, потому что это не процент: сравнивать не с чем, любой
   * приступ дал бы «бесконечность». Порога для этого случая клиника не
   * задавала — уточняющий вопрос 12. До ответа врачу показывается факт, но
   * своим текстом, а не как «стало больше на N %».
   */
  seizuresAppeared: boolean;
}

const MS_PER_DAY = 24 * 60 * 60 * 1000;

/**
 * Календарных суток между двумя датами сервера.
 *
 * Обе даты уже местные для клиники (`date` и `last_reading_on` сводки), и здесь
 * они только вычитаются. Раньше вместо дня записи бралась её метка времени и
 * переводилась в пояс браузера: у врача в Москве замер в 00:30 по Ташкенту
 * падал на предыдущие сутки, в Токио вечерний — на следующие. При строгом
 * пороге в двое суток такой сдвиг — половина порога.
 */
function calendarDaysBetween(from: Date, to: Date): number {
  const start = Date.UTC(from.getFullYear(), from.getMonth(), from.getDate());
  const end = Date.UTC(to.getFullYear(), to.getMonth(), to.getDate());
  return Math.round((end - start) / MS_PER_DAY);
}

/**
 * Флаги строки списка пациентов (раздел 8.3 ТЗ, «Врач / Пациенты»).
 *
 * null — судить не о чем: сводки ещё нет (запрос идёт или отказан) либо её дата
 * не разобралась. Пустая строка честнее, чем «данных нет» по неполученному
 * ответу.
 *
 * За «сегодня» берётся дата из самой сводки, а не часы врача: сервер собирает
 * её в часовом поясе установки, и в другом поясе браузер добавил бы сутки
 * разницы к каждому пациенту сразу.
 */
export function computePatientFlags(
  overview: PatientOverview | null,
): PatientFlags | null {
  if (overview === null) return null;

  const today = parseDateInput(overview.date);
  // Дата сводки не разобралась — судить не о чем. Раньше этот случай попадал в
  // ту же ветку, что «замеров не было вовсе», и врач видел красное «Замеров ещё
  // не было» у ребёнка, который меряется дважды в день: сбой разбора выдавался
  // за клинический факт.
  if (today === null) return null;

  // Поле пришло вместе со строгим месяцем. Старый ответ API — секунды между
  // выкатом кабинета и перезапуском сервера — о дне записи не говорит ничего,
  // и «записей не было» по нему было бы ложной красной пометкой. Судить не о чем.
  if (overview.last_reading_on === undefined) return null;

  const lastReadingOn =
    overview.last_reading_on === null
      ? null
      : parseDateInput(overview.last_reading_on);
  if (overview.last_reading_on !== null && lastReadingOn === null) return null;

  // Запись «из будущего» (часы устройства семьи спешат) — это ноль суток, а не
  // отрицательное число.
  const daysSinceLastReading =
    lastReadingOn === null
      ? null
      : Math.max(0, calendarDaysBetween(lastReadingOn, today));

  const tolerance = overview.day?.tolerance ?? null;
  const noPrescription = (overview.prescription ?? null) === null;
  // Отсутствие поля (старая версия API в секунды между выкатами) читается как
  // обычный контроль — то есть как было до ответа клиники, а не как тревога.
  const strictMonitoring = overview.monitoring_phase === "strict";
  const silenceThreshold = strictMonitoring
    ? STRICT_NO_DATA_FLAG_DAYS
    : NO_DATA_FLAG_DAYS;

  return {
    noPrescription,
    daysSinceLastReading,
    strictMonitoring,
    // Молчание семьи считается только там, где семье уже сказано, что делать.
    // Без назначения кетодиеты ещё нет, и «замеров нет трое суток» — не сигнал
    // о семье, а следствие того, что врач не дошёл до назначения. Флаг о
    // назначении это и говорит; второй красный значок рядом ничего не
    // добавляет, а внимание делит.
    staleData:
      !noPrescription &&
      (daysSinceLastReading === null ||
        daysSinceLastReading >= silenceThreshold),
    nutritionOff: tolerance !== null && !tolerance.ratio_within_tolerance,
    // Вердикт приходит от сервера целиком: порог «более 50 %» — медицинское
    // правило, и считать его на клиенте значило бы завести вторую копию.
    //
    // Доступ необязательный не для красоты: между выкатом фронта и перезапуском
    // API есть секунды, когда новая страница разговаривает со старым ответом.
    // Уронить из-за этого ВЕСЬ список пациентов — цена, несоразмерная одному
    // значку. Отсутствие поля читается как «нечего сказать», а не как «нет
    // роста»: и то и другое здесь означает молчание.
    seizuresGrew: overview.seizure_trend?.grew === true,
    seizuresAppeared: overview.seizure_trend?.appeared === true,
  };
}

/**
 * Вес строки для порядка по умолчанию: требующие внимания — сверху.
 *
 * Это порядок показа, а не оценка тяжести: «нет данных» помечен в ТЗ красным, а
 * отклонение питания — оранжевым, отсюда и разный вес.
 */
export function attentionRank(flags: PatientFlags | null): number {
  if (flags === null) return 0;
  return (
    // Назначение — выше всего: пока его нет, остальные флаги не о чем судить,
    // и это единственное действие, которое врач обязан сделать сам.
    (flags.noPrescription ? 4 : 0) +
    // Рост приступов — выше молчания семьи: это ухудшение течения болезни, а
    // не отсутствие записей. Ниже отсутствия назначения только потому, что без
    // назначения терапии ещё нет и сравнивать не с чем.
    (flags.seizuresGrew ? 3 : 0) +
    (flags.seizuresAppeared ? 3 : 0) +
    (flags.staleData ? 2 : 0) +
    (flags.nutritionOff ? 1 : 0)
  );
}
