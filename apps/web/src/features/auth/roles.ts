/**
 * Разделы, которые остаются доступными по ссылке, но не стоят в меню.
 *
 * Специалист работает от пациента: вход ведёт в список, а меню из трёх пунктов
 * (пациенты, база блюд, продукты) не заставляет выбирать между двумя
 * калькуляторами (`docs/AUDIT_ROLES_PATHS_2026-11.md`).
 */
export const HIDDEN_FROM_NAV: Partial<Record<Role, ReadonlySet<string>>> = {
  doctor: new Set(["calculator", "profile"]),
  dietitian: new Set(["calculator", "profile"]),
  // Пять пунктов семьи: Главная, Меню, Дневник, Отчёт, Помощник. Калькулятор и
  // рецепты открываются из меню дня, продукты — из калькулятора, «Ребёнок» и
  // профиль — из меню учётной записи.
  parent: new Set(["calculator", "recipes", "products", "child", "profile"]),
  // Администратор ведёт людей и справочники, а не клиническое содержимое:
  // продукты и рецепты ведут и загружают диетолог и врач (ADR-0064). По ссылке
  // разделы открываются — на них ведёт проверка аномалий с главной.
  admin: new Set(["products", "recipes", "profile"]),
};

export function navSectionsFor(role: Role): readonly string[] {
  const hidden = HIDDEN_FROM_NAV[role];
  return SECTIONS_BY_ROLE[role].filter((section) => !hidden?.has(section));
}
