import { describe, expect, it } from "vitest";

import source from "./useIntake.ts?raw";

/**
 * Справочник препаратов приходит одной страницей и фильтруется на клиенте.
 *
 * Пока строк три десятка, это дешевле серверного поиска. Но потолок задан
 * числом в запросе, а справочник растёт миграциями: на сто первой строке
 * подсказка в схеме лечения начнёт молча терять препараты. Тест держит границу
 * на виду — упадёт, когда число поменяют, и заставит вспомнить, что вместе с
 * ним надо решить судьбу клиентского поиска.
 */
describe("потолок справочника препаратов", () => {
  it("запрашивается ровно сто строк, и это осознанный предел", () => {
    expect(source).toContain("limit: 100");
    expect(source).toMatch(/потолок, а не «все»/);
  });
});
