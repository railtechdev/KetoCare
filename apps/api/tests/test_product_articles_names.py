"""Статьи помощника не называют кнопок и мест, которых в продукте нет.

Помощник отвечает семье текстом статей. Аудит семейного канала 26.11.2026
нашёл шесть статей с кнопками, которых давно нет: «Указать время»,
«Пропустить», «Записали вы», флажок вместо переключателя. Родитель искал на
экране то, что ему назвал помощник, и не находил. Список ниже — подписи,
которые убрали из бота и приложения; статья с любой из них роняет тест.
"""

from __future__ import annotations

from pathlib import Path

import pytest

ARTICLES = Path(__file__).resolve().parents[3] / "docs" / "knowledge-base" / "product"

#: Подпись или указатель, которых больше нет, и чем их заменили.
RETIRED = {
    "Указать время": "кнопка «🕒 Другое время» под ответом «Записано ✓»",
    "«Пропустить»": "у самочувствия одно сообщение, пропуска нет",
    "Нет связи с сервером": "«Нет связи. Проверьте интернет.» / «Нет связи. Нажмите «Повторить»…»",
    "Записали вы": "своя запись — со значком карандаша, открывается нажатием",
    "кнопки «Исправить» и «Удалить»": "нажатие на запись → «Исправить запись» / «Удалить запись»",
    "Флажок «Присылать напоминания»": "переключатель «Присылать напоминания»",
    "вкладка «Меню»": "меню — экран внутри «Сегодня» (ADR-0075)",
    "блок «Напоминания» на главной": "«Настройки» → «Напоминания»",
    "До 30 вопросов": "предел задаёт администратор, числа в статье нет",
}


def _articles() -> list[Path]:
    return sorted(ARTICLES.glob("*.md"))


def test_articles_are_found() -> None:
    assert len(_articles()) >= 20, "статьи переехали — тест смотрит не туда"


@pytest.mark.parametrize("path", _articles(), ids=lambda p: p.stem)
def test_article_names_only_existing_labels(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    found = {old: new for old, new in RETIRED.items() if old in text}
    assert not found, f"{path.name}: устаревшие подписи → {found}"
