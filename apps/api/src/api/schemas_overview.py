"""Схемы сводки для главной (раздел 5.3 ТЗ, раздел 8.3 «Родитель / Главная»).

Один ответ на весь экран: назначение, итоги дня против него, последние кетоны и
вес, приступы за сегодня. Любая часть может отсутствовать — это нормальное
состояние семьи, которая только начала вести дневник, а не ошибка.
"""

from __future__ import annotations

import datetime as dt
import enum
import uuid
from datetime import date, datetime

from pydantic import BaseModel, ConfigDict

from core.control_schedule import ControlPurpose
from core.models.enums import KetoneMethod

from .schemas import DishComputed, PrescriptionRead


class DayTolerance(BaseModel):
    """Соответствие итогов дня назначению.

    Считается `keto_engine.within_tolerance`: сами допуски — медицинские
    константы ядра (правило 2 CLAUDE.md), API их не знает и не дублирует.
    """

    #: `null` — соотношения у дня нет вовсе, и сказать о соответствии нечего.
    #: Это НЕ то же самое, что «не соответствует»: экраны показывают такой день
    #: нейтрально, а не нарушением (ADR-0037).
    ratio_within_tolerance: bool | None
    kcal_within_tolerance: bool


class ToleranceGap(enum.StrEnum):
    """Почему у дня нет вердикта о соответствии назначению.

    Причин две, и на экране они читаются по-разному: «назначения ещё нет» — это
    про то, что врач не задал цель, а «день посчитан прежней версией ядра» — про
    то, что цель есть, но сверять с ней старое число нечестно. Пока причина была
    одна на обе, кабинет говорил семье «активного назначения нет» при живом
    назначении.
    """

    #: Активного назначения нет — сравнивать итоги не с чем.
    NO_PRESCRIPTION = "no_prescription"

    #: День посчитан ядром другой ОСНОВНОЙ версии (ADR-0016, ADR-0030): числа
    #: получены по прежнему правилу, и вердикт по ним был бы утверждением о
    #: сегодняшнем правиле на вчерашних числах.
    ENGINE_CHANGED = "engine_changed"

    #: У дня не записана версия ядра (колонка допускает пустое значение).
    #: Сверять с ней нечего, но и сказать «посчитан прежней версией» нельзя:
    #: какой именно — неизвестно, а утверждать больше известного мы не станем.
    ENGINE_UNKNOWN = "engine_unknown"


class DaySummary(BaseModel):
    """Итоги дня из `menus.totals` — те же показатели, что у блюда, поэтому схема
    `DishComputed` переиспользуется, а не копируется (как в `MenuRead.totals`).

    Значения не пересчитываются при чтении: их считает ядро при сохранении меню и
    хранит вместе с `engine_version`. Второй расчёт здесь дал бы два источника
    одних и тех же чисел, которые разойдутся при первом изменении ядра.
    """

    totals: DishComputed
    # null, если вердикта нет; почему именно — в `tolerance_gap`
    tolerance: DayTolerance | None = None
    #: Заполнено ровно тогда, когда `tolerance` пуст, и наоборот.
    tolerance_gap: ToleranceGap | None = None
    engine_version: str | None = None


class DayShortfall(BaseModel):
    """Прошедший день, в который ребёнок съел заметно меньше суточной нормы.

    Ответ клиники от 09.09.2026 на вопрос 9: «Предупреждать, когда день
    завершён: что не доели и это может сказаться на состоянии ребёнка».
    Завершённым считается вчерашний день — сегодняшний ещё идёт.

    Всё посчитано здесь: и съеденное (позиции, отмеченные «съедено», расчётом
    ядра по снимкам), и норма (назначение, действовавшее в тот день), и допуск
    (`keto_engine.within_tolerance`). Экраны семьи только подставляют
    `shortfall_kcal` в текст.
    """

    date: date
    #: Сколько съедено по отметкам «съедено», ккал (округлено).
    eaten_kcal: float
    #: Суточная норма назначения, действовавшего в тот день.
    target_kcal: int
    #: Сколько не добрали до нормы, ккал (округлено). Больше допуска ядра.
    shortfall_kcal: float


class KetoneReading(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    value: float
    method: KetoneMethod
    occurred_at: datetime


class WeightReading(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    weight_kg: float
    occurred_at: datetime


class SeizuresToday(BaseModel):
    """`entries` — записей в дневнике, `count` — сумма их поля `count`.

    Разделены намеренно: одна запись может описывать серию приступов, и подменять
    число приступов числом записей — занижать клиническую картину.
    """

    model_config = ConfigDict(from_attributes=True)

    entries: int
    count: int


class SeizureTrend(BaseModel):
    """Приступы за последние семь дней против предыдущих семи.

    Ответ клиники от 09.09.2026 (вопрос 12): считать по СУММАРНОМУ числу
    приступов, порог роста — более 50 %. Не по числу записей в дневнике: одна
    запись описывает серию, и подменять одно другим — занижать картину.

    Неделя, а не месяц: врач смотрит список пациентов между приёмами, и месячное
    окно показало бы ухудшение через месяц после того, как оно началось.
    """

    model_config = ConfigDict(from_attributes=True)

    #: Суммарное число приступов за последнюю неделю (местные сутки).
    #:
    #: Это шесть ПОЛНЫХ суток плюс прошедшая часть сегодняшних, тогда как
    #: `previous` — семь полных. Асимметрия намеренная: убрать её можно только
    #: выбросив сегодняшний день, а тогда приступ, записанный утром, не считался
    #: бы до завтра — врач же открывает список именно сегодня.
    recent: int
    #: Суммарное число за предыдущие 7 полных суток — то, с чем сравнивают.
    previous: int
    #: Вырос ли показатель более чем на 50 %.
    #:
    #: `None` — сравнивать не с чем: предыдущая неделя была без приступов, и
    #: любой приступ дал бы рост «на бесконечность». Порога для этого случая
    #: клиника не задавала (см. `appeared`).
    grew: bool | None = None
    #: Приступы появились после недели без них.
    #:
    #: Отдельно от `grew`, потому что это не процент, а факт. Считать ли это
    #: тревогой наравне с ростом на 50 % — уточняющий вопрос 12 медкоманде;
    #: до ответа факт показывается, но своим текстом.
    appeared: bool = False


class MonitoringPhase(enum.StrEnum):
    """Режим наблюдения за пациентом — ответ клиники на вопрос 11.

    Строгий первый месяц терапии, дальше обычный контроль. В строгом режиме
    пометка «нет замеров» у врача загорается раньше: «даже один день молчания
    будет звонком».
    """

    #: Терапия ещё не началась: даты начала нет или она в будущем.
    BEFORE_START = "before_start"
    #: Первый месяц от начала терапии — строгое наблюдение.
    STRICT = "strict"
    #: После первого месяца — обычный контроль.
    ROUTINE = "routine"


class NextControl(BaseModel):
    """Ближайший контрольный визит (вопросы 17 и 18, ADR-0050)."""

    planned_on: date
    #: Дата прошла, а визит не отмечен. Порога «просрочки» клиника не называла.
    overdue: bool
    #: Оценка эффективности (6 месяцев) или решение о продолжении (24 месяца).
    purpose: ControlPurpose | None = None


class PatientOverview(BaseModel):
    patient_id: uuid.UUID
    # Дата, за которую посчитаны итоги и приступы, — местная (settings.tz), не UTC
    date: date
    prescription: PrescriptionRead | None = None
    # null, если меню на сегодня нет или итоги по нему ещё не сохранены
    day: DaySummary | None = None
    last_ketone: KetoneReading | None = None
    last_weight: WeightReading | None = None
    seizures_today: SeizuresToday
    #: Динамика приступов неделя к неделе; нужна врачу в списке пациентов.
    seizure_trend: SeizureTrend
    #: Календарный день последней записи, снимающей «молчание семьи»: замера
    #: кетонов, замера веса или приступа за сегодня. `None` — таких записей не было.
    #:
    #: Считается на сервере по часам клиники (`settings.tz`), а не в кабинете по
    #: `occurred_at`: пояс браузера сдвигал день замера на сутки в обе стороны.
    #:
    #: Тип через `dt.date`: имя `date` в теле класса уже занято полем выше.
    last_reading_on: dt.date | None
    #: Активирован ли доступ семьи — есть ли у ребёнка хоть один родитель
    #: (ADR-0040). Карта живёт без семьи с момента заведения на приёме до
    #: активации кода, и это штатное состояние: пометка в списке врача, а не
    #: тревога «семья молчит».
    family_activated: bool = False
    #: Когда был последний затяжной приступ (30 минут и дольше — измеренный или
    #: со слов) за последние семь дней; `None` — не было (ADR-0046, аудит C8).
    #:
    #: Флаг врачу, а не семье: экраны семьи это поле не читают, и что делать
    #: при таком приступе, им говорит клиника, а не продукт.
    prolonged_seizure_at: datetime | None = None
    #: Режим наблюдения: первый месяц терапии или обычный контроль (вопрос 11).
    #:
    #: Самой даты начала терапии в сводке нет — она лежит в медицинском профиле,
    #: закрытом семье. Но режим от неё производен, и семья, следящая за сводкой
    #: изо дня в день, увидит, в какой день он сменился. Это допущение, а не
    #: защита: оно разобрано в ADR-0031 — дата начала диеты не то, ради чего
    #: профиль закрыт, и семья начинает диету сама.
    monitoring_phase: MonitoringPhase
    #: Дата завершения кетодиетотерапии (вопрос 18, ADR-0050); `None` — ребёнок
    #: на терапии. Семья видит по ней нейтральную строку «терапия завершена»;
    #: причина завершения сюда не входит — она в медицинском профиле.
    therapy_ended_on: dt.date | None = None
    #: Ближайший несостоявшийся контрольный визит (вопрос 17); `None` — визитов
    #: в графике нет или все отмечены.
    next_control: NextControl | None = None
    #: Вчера ребёнок съел меньше суточной нормы сильнее допуска ядра (вопрос 9).
    #:
    #: `None` — недобора не было ЛИБО судить не по чему: вчера не было плана,
    #: ничего не отмечено съеденным, нет назначения или терапия завершена.
    #: Молчание в этих случаях намеренное: «недобрал 1200 ккал» про день, о
    #: котором семья просто ничего не записала, было бы ложной тревогой.
    #:
    #: Потребители — главная семьи в кабинете (`features/home`) и в Mini App
    #: (`features/home/HomeScreen.tsx`).
    yesterday_shortfall: DayShortfall | None = None
    #: Значимое снижение z-балла роста или веса от исходного (вопрос 15:
    #: ≥ 1,0 SD) хотя бы по одному показателю ВОЗ.
    #:
    #: `None` — не считалось: оценка по ВОЗ — интерпретация, её видят врач и
    #: диетолог (раздел «Рост и вес» карты), и семье поле не отдаётся. Считает
    #: та же функция, что раздел карты (`services.growth.assess_patient`).
    #: Потребитель — пометки списка пациентов (`features/doctor/flags.ts`).
    growth_significant_drop: bool | None = None
