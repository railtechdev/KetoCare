"""Аутентификация Telegram-бота (раздел 5.2 ТЗ, [ADR-0009](../../../../../docs/adr/0009-telegram-bot-authentication.md)).

Два разных ключа с разными правами:

* **Сервисный токен** `BOT_API_TOKEN` — говорит «это наш бот», и только. Открывает
  ровно две ручки: погашение кода привязки и обмен секрета привязки на сессию.
  Ни одной ручки с данными пациента им открыть нельзя.
* **Секрет привязки** — выдаётся боту один раз при привязке чата и хранится у
  бота. Вместе с сервисным токеном обменивается на краткоживущий access-токен,
  суженный до одного ребёнка.

Так утечка одной статичной строки из окружения (лог, дамп env, CI, Sentry) не
даёт ни одной записи о пациентах: без секретов привязок она бесполезна.
"""

from __future__ import annotations

import hmac

from fastapi import Request

from core.config import get_settings

from ..errors import ApiError, ErrorCode

BOT_TOKEN_HEADER = "X-Bot-Token"

# Маршруты, доступные токену канала `bot`. Список закрытый: чего в нём нет, то
# запрещено. Роль `parent` сама по себе открывает и назначения, и отчёты, и
# профиль ребёнка — раздел 7.5 ТЗ прямо запрещает боту показывать параметры
# назначения, а утёкший ботовый токен иначе выгружал бы клиническую историю
# целиком.
#
# Список именно разрешающий, а не запрещающий: новая ручка, о которой забыли,
# должна оказаться закрытой для бота, а не открытой.
#
# Пути — шаблоны маршрутов (`path_format`), с параметрами в фигурных скобках, а
# не конкретные адреса. Префикса `/api/v1` в них нет: версия навешивается
# внешним роутером, и до маршрута она не доходит. Если это когда-нибудь
# изменится, список перестанет совпадать и закроет боту всё — то есть
# сломается в безопасную сторону, а `test_full_flow_writes_diary_entry`
# поймает это первым же прогоном.
BOT_ALLOWED_ROUTES: frozenset[tuple[str, str]] = frozenset(
    {
        # Дневники — то, ради чего бот и нужен (раздел 7.3 ТЗ). Только запись:
        # читать дневник в боте сценарии не предусматривают.
        ("POST", "/patients/{patient_id}/logs/seizures"),
        ("POST", "/patients/{patient_id}/logs/ketones"),
        ("POST", "/patients/{patient_id}/logs/weight"),
        ("POST", "/patients/{patient_id}/logs/medications"),
        ("POST", "/patients/{patient_id}/logs/meals"),
        ("POST", "/patients/{patient_id}/logs/side-effects"),
        # Сценарий «Еда → из меню на сегодня»: показать позиции и отметить съеденное.
        ("GET", "/patients/{patient_id}/menus"),
        ("POST", "/patients/{patient_id}/menus/items/{item_id}/eaten"),
        # Сценарий «Еда → свободный текст» (раздел 10.3 ТЗ): разбор фразы.
        # Ручка ничего не сохраняет и данных пациента не отдаёт — она их
        # принимает; запись появляется отдельным `POST .../logs/meals`, который
        # уже в списке.
        ("POST", "/ai/parse"),
        # Справочники для кнопок FSM. Клинических данных в них нет.
        ("GET", "/dictionaries/seizure-types"),
        ("GET", "/dictionaries/ketone-methods"),
    }
)


def verify_bot_service_token(request: Request) -> None:
    """Проверяет сервисный токен бота. Ничего не возвращает: это не личность.

    Личность появляется только после предъявления секрета привязки — сервисный
    токен сам по себе не соответствует ни одному пользователю.
    """

    expected = get_settings().bot_api_token
    if not expected:
        # Пустая настройка означает выключенный канал бота. Без этой проверки
        # пустой заголовок совпал бы с пустым ожидаемым значением, и канал был
        # бы открыт всем на любом стенде, где переменную не задали.
        raise ApiError(ErrorCode.UNAUTHORIZED, "Канал бота не настроен.")

    presented = request.headers.get(BOT_TOKEN_HEADER, "")
    # compare_digest, а не ==: сравнение строк выходит на первом различии и
    # выдаёт длину общего префикса временем ответа.
    if not presented or not hmac.compare_digest(presented, expected):
        raise ApiError(ErrorCode.UNAUTHORIZED, "Сервисный токен недействителен.")


def assert_route_allowed_for_bot(request: Request) -> None:
    """Закрывает ботовому токену всё, кроме списка выше.

    Вызывается из `get_current_user` — единственного места, через которое
    проходит любой пользовательский токен. Проверка в зависимости, которую надо
    не забыть добавить к ручке, рано или поздно окажется забытой.

    `request.scope["route"]` кладёт FastAPI при разрешении маршрута, до вызова
    зависимостей. Если маршрута в scope нет (такого на практике не бывает —
    зависимости выполняются уже после его выбора), считаем запрет: неизвестный
    маршрут не должен оказываться разрешённым.
    """

    route = request.scope.get("route")
    path_format = getattr(route, "path_format", None)
    if path_format is None or (request.method, path_format) not in BOT_ALLOWED_ROUTES:
        raise ApiError(ErrorCode.FORBIDDEN, "Это действие недоступно из Telegram-бота.")
