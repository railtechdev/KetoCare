"""Местное «сегодня» — одно на всё API.

Часовой пояс берётся из настроек установки (`settings.tz`), а не из окружения
процесса. В UTC+5 после 19:00 местных суток UTC-дата уже другая: по UTC-дате
семья поздним вечером увидела бы пустой «завтрашний» день вместо своих итогов, а
дата последнего приступа, введённая вечером, была бы отвергнута как будущая.

Отдельным модулем, потому что читателей два и они не связаны: сводка дня и
проверка анкеты. Наивный `date.today()` в одном из них уже разошёлся бы с другим
— он зависит от переменной `TZ` процесса, а не от настроек клиники, и молчаливо
верен ровно до первого запуска без этой переменной.
"""

from __future__ import annotations

from datetime import date, datetime
from zoneinfo import ZoneInfo

from core.config import get_settings


def local_today() -> date:
    """Сегодняшняя дата в часовом поясе установки."""

    return datetime.now(ZoneInfo(get_settings().tz)).date()
