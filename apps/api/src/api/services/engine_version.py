"""Сравнение версий расчётного ядра — в одном месте на всё API.

Правило одно: **значимо расходятся только ОСНОВНЫЕ версии.** Major означает, что
изменились сами числа (с 1.0.0 соотношение считается по чистым углеводам,
ADR-0030), а minor и patch поведения не меняют — 0.3.0 → 0.4.0 добавила вклад
позиций и не тронула ни одного итога.

Из этого следует, что говорить о сохранённых расчётах прежней основной версии
нельзя ничего утвердительного: снимок фиксирует то, что было (ADR-0016), и
вердикт «в допуске» по нему был бы сегодняшним утверждением о вчерашних числах.

Копий этой функции быть не должно. Их было две — в сводке дня и в сводке врача,
— и они разошлись: `/overview` перестал выносить вердикт дню чужой версии, а
сводка продолжала усреднять отклонения соотношения через границу правила и
отдавать среднее модели, а потом врачу.
"""

from __future__ import annotations

from keto_engine import ENGINE_VERSION


def major(version: str) -> str:
    """Старшая часть версии: «1.0.0» → «1».

    Пустую версию сюда не передают: у неё нет старшей части, а случай «версия не
    записана» означает другое и разбирается на месте.
    """

    return version.split(".", 1)[0]


def comparable_to_current(version: str | None) -> bool:
    """Можно ли сравнивать числа этой версии с сегодняшними.

    Пустая версия — нельзя: неизвестно, по какому правилу они посчитаны, а
    догадка здесь стоит дороже молчания.
    """

    return version is not None and major(version) == major(ENGINE_VERSION)
