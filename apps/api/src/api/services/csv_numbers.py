"""Число из ячейки CSV — строже, чем его понимает `float`.

`float` разбирает гораздо больше, чем пишут в таблицах составов: «nan», «inf»,
«1e2», «1_00», «+5». Каждое из этого проходило импорт:

- NaN не проходит ни одно сравнение — ни «< 0», ни «> предела», ни проверку
  суммы, — и продукт с жирами «nan» или граммовка «nan» загружались без ошибок,
  ломая каждый расчёт, где встречались;
- «1_00» превращалось в 100, а «8_1» — в 81: опечатка в ячейке становилась
  другим числом без единого слова об этом.

Поэтому ячейка сначала сверяется с видом десятичной дроби, и только потом
отдаётся `float`. Одна функция на оба импорта (продукты и рецепты): у двух
копий правило однажды разошлось бы.
"""

from __future__ import annotations

import math
import re

#: Десятичная дробь, как её пишет таблица: цифры, одна точка, необязательный
#: минус. Минус пропускается намеренно — отрицательное значение каждый импорт
#: отклоняет своим, более понятным текстом.
#:
#: `re.ASCII`: без него `\d` — любая цифра Юникода, и смешанное «1٥» стало бы 15.
_DECIMAL = re.compile(r"-?(?:\d+(?:\.\d*)?|\.\d+)", re.ASCII)


def parse_decimal(raw: str) -> float | None:
    """Число из ячейки или `None`, если это не десятичная дробь.

    Пробелы по краям снимаются, запятая принимается как десятичный разделитель:
    Excel в русской локали пишет дробную часть через запятую. Бесконечность из
    слишком длинной строки цифр тоже отклоняется — `float` её не запрещает.
    """

    text = raw.strip().replace(",", ".")
    if not _DECIMAL.fullmatch(text):
        return None
    value = float(text)
    return value if math.isfinite(value) else None
