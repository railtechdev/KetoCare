"""Режим наблюдения за пациентом — ответ клиники на вопрос 11.

«Давайте определим срок мониторирования пациента. Например, от начала диеты в
течение месяца должен идти строгий мониторинг, и здесь даже один день молчания
будет звонком. А после месяца — просто контроль» (09.09.2026).

Здесь решается только РЕЖИМ: первый месяц терапии или нет. Сколько дней молчания
считать сигналом в каждом режиме, решает кабинет (`features/doctor/flags.ts`):
порог жил там и раньше, и там же он подставляется в легенду пометок. Режим же
требует даты начала терапии, а она лежит в медицинском профиле, который семье
закрыт, — поэтому режим считается на сервере, и в общую для семьи и врача сводку
уходит он, а не дата.
"""

from __future__ import annotations

import calendar
from datetime import date

from ..schemas_overview import MonitoringPhase

#: Сколько календарных месяцев от начала терапии длится строгое наблюдение.
#:
#: TODO(med): вопрос 11. Клиника сказала «например, в течение месяца», и
#: «например» оставляет число открытым — уточнение заведено.
STRICT_MONITORING_MONTHS = 1


def add_months(day: date, months: int) -> date:
    """Та же дата через `months` календарных месяцев, прижатая к концу месяца.

    «Месяц от начала диеты» — календарный: с 15 марта до 15 апреля. Если такого
    числа в целевом месяце нет, берётся последний день: с 31 января — до 28
    февраля (29-го в високосный год). Считать «30 дней» значило бы подменить
    слово клиники своим числом.
    """

    month_index = day.month - 1 + months
    year = day.year + month_index // 12
    month = month_index % 12 + 1
    last_day = calendar.monthrange(year, month)[1]
    return date(year, month, min(day.day, last_day))


def monitoring_phase(*, started_on: date | None, today: date) -> MonitoringPhase:
    """Режим наблюдения на сегодня.

    - `before_start` — терапия не началась: даты нет вовсе или она в будущем;
    - `strict` — первый месяц: `started_on <= today < started_on + 1 месяц`;
    - `routine` — после.

    День начала — уже терапия (то же строгое сравнение, что в правиле про
    исходную частоту приступов), а день, в который месяц истекает, — уже
    обычный контроль: старт 15 марта, последний день строгого режима 14 апреля.
    """

    if started_on is None or today < started_on:
        return MonitoringPhase.BEFORE_START
    if today < add_months(started_on, STRICT_MONITORING_MONTHS):
        return MonitoringPhase.STRICT
    return MonitoringPhase.ROUTINE
