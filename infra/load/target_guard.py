"""Отказ гонять нагрузку по чужому адресу.

Отдельным модулем, а не в самом профиле, по причине зависимостей: `locustfile.py`
импортирует `locust` и `requests`, которых нет ни в общем окружении воркспейса,
ни в `pyproject.toml` — профиль ставится отдельно (infra/load/README.md). Тест,
грузящий профиль целиком, проверял бы наличие зависимости, а не защиту, и падал
бы в CI. Здесь же — чистая функция от строки и окружения.

Прежде на этом месте стояла ПЕЧАТЬ: «цель похожа на настоящий стенд», после
которой прогон продолжался. Правило жило в тексте и ни в одном исполняемом виде,
при том что профиль ПИШЕТ записи в дневник: на стенде это записи живой семьи, и
убрать их можно только `core.tools.erase_patient`.

Список адресов БЕЛЫЙ — как у `core.tools.db_guard`, и по той же причине. Первая
редакция этой защиты отсеивала «railtech» и `https://`, и мимо неё проходили
`http://prod-api.internal:8001` и адрес по IP, зато `https://localhost:8443`
отвергался ложно. Вдобавок слово «railtech» временное: docs/DEPLOY.md говорит,
что после MVP проект переезжает на сервер клиента — чёрный список перестал бы
значить что-либо, оставаясь на вид рабочим.

Чего этой проверкой не закрыть: `ssh -L 8001:127.0.0.1:8001` делает боевой API
неотличимым от локального. Тот же класс назван у `db_guard` для базы.
"""

from __future__ import annotations

import os
from urllib.parse import urlsplit

#: Явное разрешение на нелокальную цель — как у сидов. Значением задаётся САМ
#: адрес: подтверждение должно быть конкретным, иначе строка в профиле оболочки
#: снимает защиту навсегда и для любой цели.
ALLOW_TARGET = "LOAD_ALLOW_TARGET"

#: Разрешённые адреса: только петля. Пустая строка — «цель не задана»: locust в
#: этом случае и так никуда не пойдёт, а отказ был бы про не тот предмет.
LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1", ""})


def _hostname(target: str) -> str:
    """Хост из адреса цели.

    Схема добавляется, если её нет: `urlsplit("evil.com:8001")` разбирает строку
    как «схема evil.com, путь 8001» и хоста не даёт вовсе — без этого чужая цель
    без схемы выглядела бы локальной.
    """
    parsed = urlsplit(target if "://" in target else f"http://{target}")
    # Регистр приводить не нужно: `hostname` отдаёт хост уже в нижнем
    # (проверено — `HTTP://LOCALHOST` даёт `localhost`). Свой `.lower()` здесь
    # стоял и был мёртвым: мутация «снять приведение» не убивалась ничем, и это
    # признак не дыры в тестах, а лишнего кода.
    return (parsed.hostname or "").strip().rstrip(".")


def refuse_foreign_target(host: str) -> None:
    """Прервать прогон, если цель не локальная и не подтверждена поимённо."""
    target = (host or "").strip().rstrip("/")
    if _hostname(target) in LOCAL_HOSTS:
        return
    allowed = os.environ.get(ALLOW_TARGET, "").strip().rstrip("/")
    if allowed != "" and allowed.lower() == target.lower():
        return
    raise RuntimeError(
        f"Цель «{target}» не похожа на локальную, а {ALLOW_TARGET} её не "
        "подтверждает.\n"
        "Нагрузочный прогон ПИШЕТ записи в дневник: на стенде это записи живой "
        "семьи, и убрать их можно только `core.tools.erase_patient`.\n"
        f"Гоняйте по локальной базе или передайте {ALLOW_TARGET}=<адрес> той же "
        "командой: профиль читает окружение процесса."
    )
