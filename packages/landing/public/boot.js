// Ставит тему и признак «скрипты есть» до первой отрисовки.
//
// Отдельным файлом, а не инлайновым скриптом в разметке, — ради политики
// содержимого. С `script-src 'self'` инлайновый скрипт не выполнится, а хеш
// инлайна в политике был бы третьим местом, которое нужно править вместе с
// текстом скрипта, и однажды разошёлся бы с ним молча.
//
// Тема: сохранённый выбор посетителя, иначе — настройка системы. Без скриптов
// сайт светлый: тёмные цвета объявлены только под `data-theme="dark"`, и
// второго их списка под медиазапросом нет — два списка однажды разошлись бы.
//
// Файл лежит в `public/`, поэтому имя без хеша содержимого и кэшируется как
// `no-cache` — он и весит меньше килобайта.
/* global document, localStorage, window, setTimeout */
(function () {
  var de = document.documentElement;
  var theme = "light";
  try {
    var stored = localStorage.getItem("kc-theme");
    if (stored === "dark" || stored === "light") {
      theme = stored;
    } else if (
      window.matchMedia &&
      window.matchMedia("(prefers-color-scheme: dark)").matches
    ) {
      theme = "dark";
    }
  } catch {
    // Хранилище или matchMedia недоступны — остаётся светлая тема.
  }
  de.setAttribute("data-theme", theme);

  // `js` — скрипты есть: форма заявки вместо ссылки на почту, меню-значок.
  de.classList.add("js");

  // Страховка. Если основной модуль не выполнился за три секунды (ошибка,
  // оборванная загрузка, старый браузер), снимаем признак: пусть с почтой
  // вместо формы и с раскрытым меню, но страница будет рабочей.
  setTimeout(function () {
    if (de.dataset.siteReady !== "1") de.classList.remove("js");
  }, 3000);
})();
