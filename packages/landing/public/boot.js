// Ставит классы до первой отрисовки: иначе блоки, скрытые до появления при
// прокрутке, успевают мигнуть.
//
// Отдельным файлом, а не инлайновым скриптом в разметке, — ради политики
// содержимого. С `script-src 'self'` инлайновый скрипт не выполнится, а без
// политики лендинг остаётся единственной страницей проекта без неё. Хеш
// инлайна в политике был бы третьим местом, которое нужно править вместе с
// текстом скрипта, и однажды разошёлся бы с ним молча.
//
// Файл лежит в `public/`, поэтому имя без хеша содержимого и кэшируется как
// `no-cache` — он и весит меньше килобайта.
(function () {
  var de = document.documentElement;
  // `js` — скрипты вообще есть (форма заявки вместо ссылки на почту);
  // `js-anim` — можно прятать блоки до их появления при прокрутке.
  de.classList.add("js", "js-anim");

  // Страховка. Прятать содержимое, рассчитывая показать его скриптом, — ставка
  // на то, что скрипт выполнится. Если основной модуль не выполнился за три
  // секунды (ошибка, оборванная загрузка, старый браузер), снимаем оба класса:
  // пусть без анимации и с почтой вместо формы, но страница будет читаемой, а
  // не пустой.
  setTimeout(function () {
    if (de.dataset.siteReady !== "1") de.classList.remove("js", "js-anim");
  }, 3000);
})();
