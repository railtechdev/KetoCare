import type { ReactNode } from "react";

import { cn } from "../lib/cn";

export interface ActionReasonProps {
  /** Чего не хватает. `null` — препятствия нет, строка пуста */
  children: ReactNode;
  /** Идентификатор для `aria-describedby` у кнопки */
  id: string;
  className?: string;
}

/**
 * Почему кнопка не нажимается.
 *
 * **Отключённая кнопка обязана называть причину** (правило П44 канона).
 * Экран знает, чего не хватает, — и молчит: серый прямоугольник, и человек
 * решает, что сломалось. Так заказчица не дошла до подбора граммовки —
 * единственного, чего нет у программы, к которой она привыкла: она набрала в
 * поиске продуктов название блюда, состав остался пустым, кнопка осталась
 * серой, и на экране не было ни слова о том, почему.
 *
 * Строка стоит ПОД кнопкой, а не вместо неё: кнопку видно, и видно, что она
 * есть и заработает.
 *
 * **Область живёт постоянно, даже когда причины нет.** `role="status"`,
 * добавленный в разметку вместе с текстом, значительная часть программ чтения
 * с экрана не озвучивает: живая область обязана существовать ДО того, как в
 * ней что-то появится. Поэтому пустой абзац остаётся в разметке — высоты он не
 * занимает.
 *
 * Отдельно стоит знать границу: у кнопки с настоящим `disabled` описание
 * читается не всегда — она вне порядка табуляции, и обходом с клавиатуры до
 * неё не добраться. Работает здесь именно живая область: причина произносится в
 * момент появления. `aria-disabled` вместо `disabled` вернул бы кнопку в обход,
 * но сделал бы её нажимаемой — для действия, которое всё равно нечем
 * выполнить, это хуже.
 *
 * Это не ошибка: человек ничего не нарушил, он ещё не закончил. Поэтому
 * обычная подпись, а не `destructive` и не значок тревоги.
 */
export function ActionReason({ children, id, className }: ActionReasonProps) {
  return (
    <p
      id={id}
      role="status"
      // Причина называет продукт из справочника («Масса продукта «…» больше…»),
      // а название бывает словом без пробелов.
      className={cn("m-0 text-sm break-words text-muted-foreground", className)}
    >
      {children}
    </p>
  );
}
