import type { ReactNode } from "react";

import { cn } from "../../lib/cn";

export interface WorkspaceProps {
  /**
   * Навигация по разделам открытого предмета. Ставится в `<nav>` с подписью:
   * на экране уже есть навигация приложения, и два безымянных ориентира
   * различались бы только порядком.
   */
  nav: ReactNode;
  /** Подпись навигации для скринридера */
  navLabel: string;
  /** Содержимое открытого раздела */
  children: ReactNode;
  className?: string;
}

/**
 * Рабочее место: собственная навигация предмета рядом с его содержимым.
 *
 * Отличается от `SplitView` тем, ради чего заведён. `SplitView` показывает
 * ПЕРЕЧЕНЬ рядом с открытым предметом и на узком экране перечень убирает — там
 * это правильно: перечень отвечает на вопрос «кто следующий», и на телефоне
 * ответ на него стоит одного перехода назад. Здесь колонка — это навигация
 * САМОГО предмета, единственный способ перейти из его сводки в его назначение.
 * Убрать её на узком экране значило бы оставить экран без навигации вовсе,
 * поэтому она не исчезает: ниже точки расхождения она встаёт над содержимым.
 *
 * Отсюда и разное устройство: `SplitView` ветвится в JS (лишней половины на
 * телефоне не существует), а здесь обе части нужны всегда, и раскладку целиком
 * решает сетка.
 *
 * **Точка расхождения одна и не настраивается — 80rem.** Ширина колонки
 * (14rem) и того, что рядом с ней встаёт, — это одно решение: проп `from`
 * означал бы, что колонка и её содержимое могут разойтись во мнении о ширине,
 * а разойдясь, они не уронят ни одного теста.
 *
 * Именно 80rem, а не 64rem, — по замеру. На окне 1024 px, отдав 14rem колонке,
 * содержимому остаётся 664 px: дневник врача с шестью столбцами в них не
 * помещается. Ниже точки расхождения навигация ложится строкой над
 * содержимым, и оно получает те же ~900 px, что и на 1280 рядом с колонкой, —
 * переход выходит ровным, без провала посередине. Та же точка, что у
 * `SplitView`, и по той же причине.
 */
export function Workspace({
  nav,
  navLabel,
  children,
  className,
}: WorkspaceProps) {
  return (
    <div
      className={cn(
        "grid items-start gap-screen",
        "xl:grid-cols-[var(--container-nav)_minmax(0,1fr)]",
        className,
      )}
    >
      {/* Навигация идёт раньше содержимого и в разметке: с неё начинают и
          глазом, и клавиатурой, и на узком экране она обязана оказаться над
          содержимым, а не под ним. */}
      <nav
        aria-label={navLabel}
        className="flex min-w-0 flex-col gap-block xl:sticky xl:top-20 xl:self-start"
      >
        {nav}
      </nav>
      <div className="flex min-w-0 flex-col gap-screen">{children}</div>
    </div>
  );
}

/**
 * Список пунктов навигации рабочего места.
 *
 * Столбец рядом с содержимым и строка с переносом над ним — одно и то же
 * перечисление, поэтому оно и объявлено один раз. Пункты не прячутся в
 * прокрутку: спрятанный пункт не находят, и это тот же довод, по которому
 * `TabsBar` переносит вкладки по строкам, а не листает их.
 *
 * Разметка — `<ul>`: перечисление ссылок обязано быть перечислением и для
 * скринридера, иначе он не назовёт, сколько их и какая по счёту открыта.
 */
export function WorkspaceNav({
  children,
  className,
}: {
  children: ReactNode;
  className?: string;
}) {
  return (
    <ul
      className={cn(
        "m-0 flex list-none flex-wrap gap-1 p-0 xl:flex-col xl:flex-nowrap",
        className,
      )}
    >
      {children}
    </ul>
  );
}
