import type { ReactNode } from "react";

import { cn } from "../../lib/cn";
import { useBreakpoint, type Breakpoint } from "../../lib/useBreakpoint";

const RAIL_AT = {
  xl: "xl:grid-cols-[var(--container-aside)_minmax(0,1fr)]",
  "2xl": "2xl:grid-cols-[var(--container-aside)_minmax(0,1fr)]",
} as const;

export interface SplitViewProps {
  /**
   * Полный список — экран, когда ничего не выбрано. Со своим заголовком,
   * отбором и первичным действием.
   */
  list: ReactNode;
  /**
   * Короткий перечень для узкой колонки: он стоит РЯДОМ с открытым предметом и
   * потому не повторяет полный список. Заголовок у него уровня блока: заголовок
   * экрана уже занят именем открытого предмета (правило П24 канона).
   */
  rail: ReactNode;
  /** Открытый предмет; `null` — не выбран ничего */
  detail: ReactNode | null;
  /** С какой ширины окна перечень и предмет стоят рядом */
  from?: Extract<Breakpoint, "xl" | "2xl">;
  className?: string;
}

/**
 * Перечень и открытый предмет: рядом на широком экране, по очереди на узком.
 *
 * Зачем: на мониторе 1920 врач открывал карту пациента шириной 1152 px, имея
 * 488 px пустоты справа, и возвращался к списку через «Назад» каждый раз, когда
 * нужно было перейти к следующему пациенту. Широкий экран умеет ровно одно, чего
 * не умеет узкий, — показывать два предмета сразу; до этого компонента
 * приложение этим не пользовалось нигде.
 *
 * **Разветвление в JS, а не классом `hidden`.** Обе половины в разметке
 * означали бы, что на телефоне список пациентов остаётся в дереве доступности
 * под открытой картой: скринридер читает его, поиск по странице находит,
 * `Tab` уводит в него. Здесь на узком экране лишней половины не существует
 * вовсе — ровно то поведение, что было до компонента.
 *
 * Адрес при этом один и тот же на обеих ширинах: что открыто, знает вызывающий
 * экран из своего параметра адреса (правило П1 канона). Ссылка, присланная
 * коллеге с широкого монитора, на телефоне откроет тот же предмет.
 */
export function SplitView({
  list,
  rail,
  detail,
  from = "xl",
  className,
}: SplitViewProps) {
  const wide = useBreakpoint(from);

  // Ничего не выбрано — экран списка, во всю ширину. Пустая половина рядом со
  // списком показывала бы место, отведённое под то, чего нет.
  if (detail === null) return <>{list}</>;

  if (!wide) return <>{detail}</>;

  return (
    <div
      className={cn("grid items-start gap-screen", RAIL_AT[from], className)}
    >
      <div className="sticky top-20 flex min-w-0 flex-col gap-block">
        {rail}
      </div>
      <div className="flex min-w-0 flex-col gap-screen">{detail}</div>
    </div>
  );
}
