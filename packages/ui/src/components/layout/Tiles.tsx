import type { HTMLAttributes, ReactNode } from "react";

import { cn } from "../../lib/cn";

/**
 * Наименьшая ширина плитки.
 *
 * `min(…,100%)` внутри `minmax` обязателен: без него плитка шириной 22rem шире
 * экрана телефона, и сетка вылезает горизонтальной прокруткой — молча, без
 * ошибки где бы то ни было. Это самая частая ошибка в `auto-fit`.
 */
const MIN_WIDTH = {
  fit: {
    sm: "grid-cols-[repeat(auto-fit,minmax(min(16rem,100%),1fr))]",
    md: "grid-cols-[repeat(auto-fit,minmax(min(22rem,100%),1fr))]",
    lg: "grid-cols-[repeat(auto-fit,minmax(min(28rem,100%),1fr))]",
  },
  fill: {
    sm: "grid-cols-[repeat(auto-fill,minmax(min(16rem,100%),1fr))]",
    md: "grid-cols-[repeat(auto-fill,minmax(min(22rem,100%),1fr))]",
    lg: "grid-cols-[repeat(auto-fill,minmax(min(28rem,100%),1fr))]",
  },
} as const;

export interface TilesProps extends HTMLAttributes<HTMLElement> {
  /** Наименьшая ширина плитки; столбцов будет столько, сколько влезет */
  min?: keyof (typeof MIN_WIDTH)["fit"];
  /**
   * `fit` — плитки растягиваются и заполняют строку. Для наборов известного
   * размера: три блока отчёта, два последних замера.
   *
   * `fill` — плитка держит свою ширину, лишние столбцы остаются пустыми. Для
   * перечней переменной длины: одна карточка рецепта при `fit` растягивалась на
   * всю строку в 1030 px вместе с местом под фотографию.
   */
  columns?: keyof typeof MIN_WIDTH;
  /**
   * `ul` — когда плитки это перечень однородных предметов (записи дневника,
   * карточки рецептов). Тогда каждый ребёнок обязан быть `li`.
   */
  as?: "div" | "ul";
  /** Метка для тестов; в остальном компонент принимает обычные атрибуты. */
  "data-testid"?: string;
  className?: string;
  children: ReactNode;
}

/**
 * Равноправные блоки рядом: столько столбцов, сколько влезает.
 *
 * `auto-fit` вместо брейкпоинтов — по той же причине, что и в `MetricRow`:
 * блок не знает, где он стоит. Один и тот же перечень встречается во всю
 * ширину экрана, во вкладке карты пациента и в приставной колонке, а
 * раскладка, записанная через `sm:grid-cols-2`, спрашивает о ширине ОКНА и во
 * всех трёх местах отвечает одинаково неверно.
 *
 * Порядок остаётся линейным — слева направо, потом вниз, — поэтому сетка
 * годится для хронологии и не годится там, где важна ровно одна колонка
 * (шаги формы, связный текст).
 *
 * `columns` различает два случая, и разница видна только на коротком перечне:
 * при `auto-fit` пустые дорожки схлопываются, и единственная плитка занимает
 * строку целиком — карточка рецепта растягивалась на 1030 px вместе с местом
 * под фотографию. При `auto-fill` дорожки остаются, и плитка держит ширину.
 */
export function Tiles({
  min = "md",
  columns = "fit",
  as = "div",
  className,
  children,
  ...rest
}: TilesProps) {
  const Tag = as;

  return (
    <Tag
      className={cn(
        "grid gap-block",
        MIN_WIDTH[columns][min],
        as === "ul" && "m-0 list-none p-0",
        className,
      )}
      {...rest}
    >
      {children}
    </Tag>
  );
}
