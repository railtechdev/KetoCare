/**
 * Отказ помощника — не ответ.
 *
 * Подпись под ответом утверждает происхождение: «Ответ по материалам
 * приложения». Под отказом это утверждение ложно — ответа по материалам не
 * было ни в одном из случаев: постфильтр заменил текст шаблоном, материала в
 * базе знаний не нашлось, исчерпан суточный предел вопросов или помощник
 * недоступен. Все их воркер помечает `blocked`, недоступность — ещё и
 * `status: "failed"`; статей (`sources`) отказ не несёт никогда, поэтому
 * скрывается вся подпись целиком, а не половина.
 *
 * Правило живёт в ките, а не в экранах: кабинет и Mini App обязаны считать
 * отказом одно и то же. Раздел 10.4 ТЗ требует дисклеймер под каждым ОТВЕТОМ,
 * и толкование «отказ не ответ» записано в ADR-0022 — экран его не толкует.
 */
export interface AssistantMessageSignals {
  /** `pending` | `done` | `failed` — состояние сообщения помощника */
  status: string;
  /** Ответ заменён шаблоном (постфильтр, пустая база, предел, недоступность) */
  blocked?: boolean;
}

export function isRefusal(message: AssistantMessageSignals): boolean {
  return message.blocked === true || message.status === "failed";
}
