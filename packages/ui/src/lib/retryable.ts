/**
 * Отказ, который может пройти при повторе того же запроса.
 *
 * Правило П15 канона: у состояния ошибки есть «Повторить». Но предлагать повтор
 * там, где он заведомо не сработает, — обман: отказ по данным
 * (`validation_error`), по правам (`forbidden`) или из-за отсутствия записи
 * (`not_found`) при том же вводе повторится слово в слово. Повтор имеет смысл
 * при сбое: ответа нет вовсе (сеть, прокси — кода в теле нет), внутренняя
 * ошибка сервера или превышена частота запросов.
 *
 * В ките, а не в экране: кабинет и Mini App показывают один и тот же расчёт
 * одной семье, и предлагать повтор в одном месте, а в другом нет, нельзя.
 */
export const RETRYABLE_ERROR_CODES = ["internal", "rate_limited"] as const;

export function canRetry(code: string | null): boolean {
  return (
    code === null || (RETRYABLE_ERROR_CODES as readonly string[]).includes(code)
  );
}
