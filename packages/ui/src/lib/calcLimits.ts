/**
 * Границы ввода калькулятора — одни на все каналы.
 *
 * **Предел массы позиции.** Сервер не принимает в расчёт позицию тяжелее 5000 г
 * (`CALC_GRAMS_MAX` в `apps/api/src/api/schemas_calc.py`, та же граница, что у
 * состава рецепта). До этой проверки поле граммов принимало любое число: в
 * кабинете и в Mini App показатели блюда пропадали, а на их месте стоял общий
 * отказ «проверьте правильность заполнения полей» — без слова о том, какое
 * поле и какой предел.
 *
 * Копия числа здесь — не второй источник истины: расходиться ей не даёт тест
 * API (`test_calc_endpoints.py`, `TestGramsLimitMirroredInKit`), который читает
 * этот файл и сверяет значение со схемой. Поменяли предел на сервере — упадёт
 * тест, а не экран.
 */
export const CALC_GRAMS_MAX = 5000;

/** Масса, которую расчёт не примет. Сам предел допустим: сервер проверяет `le`. */
export function exceedsCalcGrams(grams: number): boolean {
  return grams > CALC_GRAMS_MAX;
}
