/**
 * Цель одного приёма пищи из суточного назначения — одна на все каналы.
 *
 * Живёт в ките, а не в экране, потому что это **медицинское допущение**, а не
 * вёрстка: кабинет и Mini App показывают его одной и той же семье про одного и
 * того же ребёнка, и две копии означали бы, что цель приёма зависит от того,
 * откуда родитель смотрит. Ответ медкоманды правит эту функцию, и только её.
 *
 * **Допущение: суточная норма делится на приёмы РАВНОМЕРНО.** Оно не выведено
 * из спецификации расчёта и не подтверждено медицинской командой — вопрос 24 в
 * `docs/medical/OPEN_QUESTIONS.md` открыт.
 *
 * Откуда взято: так делает KetoDietCalculator — система, в которой клиника
 * работает сегодня (`docs/AUDIT_KDC.md`). В его разделе Diet Calculations стоит
 * «Divide macros into N meals per day», и рядом печатается колонка «Per Meal /
 * Feeding (g)» — ровно суточные макросы, делённые на число приёмов. Решение
 * принято заказчиком 08.09.2026: «не будем ждать от медкоманды и подсмотрим
 * решение у KDC». Разбор — ADR-0028.
 *
 * Почему это лучше прежнего состояния, а не хуже: до этого в кабинете жила
 * зашитая константа 400 ккал, подписанная как «задаётся вами». Пользователь её
 * не задавал, и калькулятор объявлял блюдо не попавшим в цель, которую сам же и
 * выдумал. Деление хотя бы выведено из назначения ребёнка и показано на экране
 * арифметикой: «1200 ÷ 4 = 300».
 *
 * TODO(med): подтвердить у медицинской команды равномерное распределение
 * суточной нормы по приёмам (вопрос 24). Если ответ будет иным — правится
 * только эта функция.
 */

export interface PrescriptionTargets {
  ratio: number;
  kcal_per_day: number;
  meals_per_day: number;
}

export interface MealTargets {
  ratio: number;
  kcal: number;
}

export function mealTargetsFrom(
  prescription: PrescriptionTargets | null | undefined,
): MealTargets | null {
  if (!prescription) return null;
  // Ноль приёмов делил бы на ноль, а отрицательное число приёмов не бывает:
  // и то и другое — «цели нет», а не «цель ноль».
  if (prescription.meals_per_day <= 0) return null;

  return {
    ratio: prescription.ratio,
    // До целого: калорийность приёма — ориентир для взвешивания, и «287.5 ккал»
    // точнее не делает, а читается хуже.
    kcal: Math.round(prescription.kcal_per_day / prescription.meals_per_day),
  };
}
