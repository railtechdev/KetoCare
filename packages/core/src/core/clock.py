"""Местное «сегодня» — одно на весь продукт.

Часовой пояс берётся из настроек установки (`settings.tz`), а не из окружения
процесса. В UTC+5 после 19:00 местных суток UTC-дата уже другая: по UTC-дате
семья поздним вечером увидела бы пустой «завтрашний» день вместо своих итогов,
дата последнего приступа, введённая вечером, была бы отвергнута как будущая, а
ответ, данный в ночь перед началом терапии, посчитался бы данным уже на ней.

Живёт в `core`, а не в `apps/api`, потому что читателей три и они в разных
слоях: сводка дня, проверка анкеты и правило «до начала терапии» в репозитории.
`apps/api` переэкспортирует эту же функцию (`api.services.clock`) — второй
`datetime.now(ZoneInfo(...))` разошёлся бы с первым молча, а наивный
`date.today()` зависит от переменной `TZ` процесса, а не от настроек клиники.
"""

from __future__ import annotations

from datetime import date, datetime
from zoneinfo import ZoneInfo

from .config import get_settings


def local_tz() -> ZoneInfo:
    """Часовой пояс установки."""

    return ZoneInfo(get_settings().tz)


def local_today() -> date:
    """Сегодняшняя дата в часовом поясе установки."""

    return datetime.now(local_tz()).date()
