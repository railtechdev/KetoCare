"""Как ребёнок называется там, где полное имя лишнее (ADR-0048)."""

from __future__ import annotations


def first_name(full_name: str) -> str:
    """Имя без фамилии — первое слово из «Имя и фамилия».

    Порядок задаёт форма карты ребёнка: поле подписано «Имя и фамилия». Имя
    нужно сообщениям в чат, который ведёт двоих детей: «👶 Аня» отличает,
    про кого напоминание, а фамилии в переписке Telegram незачем (ADR-0048).
    Пустое имя возвращается как есть — подставлять за него ничего нельзя.
    """

    parts = full_name.split()
    return parts[0] if parts else full_name.strip()
