"""Отказ работать с чужой базой — для скриптов, которые заводят известные учётки.

Оба сида (`infra/scripts/seed_e2e.py`, `infra/scripts/seed_demo.py`) создают
пользователей с паролем из репозитория и трогают второй фактор. На своей базе
это удобство, на чужой — открытая админка и снятая защита у живых людей.

Проверка одна на оба намеренно: копия разошлась бы с оригиналом, и разошлась бы
молча — а расходиться она стала бы в защите. Различаются только описание
опасности и имя переменной разрешения: они у каждого скрипта свои, иначе одно
подтверждение открывало бы сразу два.

Модуль живёт в `core`, а не рядом со скриптами, по двум причинам. Тесты грузят
скрипты по пути (`importlib.util.spec_from_file_location`), и каталог скрипта в
путях поиска при этом не оказывается — импорт соседнего файла не разрешился бы.
А `infra/` до PR #198 не был покрыт ни ruff, ни mypy — защита осталась бы вне
всех проверок. Сейчас там есть ruff (и в CI тоже), а проверки типов по-прежнему
нет, так что довод остаётся в силе наполовину.
"""

from __future__ import annotations

import os
from typing import NoReturn

from sqlalchemy.engine import make_url

#: Разрешённые адреса: только петля.
#:
#: Список БЕЛЫЙ, а не чёрный. Прежде отсеивались три подстроки («railtech»,
#: «prod», «ketocare.uz»), и стенд вида `@db.internal:5432/ketocare_stage`
#: проверку проходил. Имён служб compose здесь НЕТ намеренно: боевой
#: `docker-compose.prod.yml` объявляет базу как `@postgres:5432/ketocare`, и
#: запись «postgres» назвала бы боевой хост локальным — ровно та ложная
#: уверенность, ради которой список и заводился. Локальный compose публикует
#: порт на хост, поэтому разработчику имена служб не нужны.
LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1", "::1"})

#: Признаки боевой строки — по ВСЕЙ строке подключения. Белый список по хосту их
#: не заменяет: туннель (`ssh -L 5432:postgres:5432`) делает чужую базу локальной
#: на вид, и тогда единственная зацепка — имя базы или пользователя.
PRODUCTION_HINTS = ("railtech", "prod", "ketocare.uz")

#: Минимальная длина пароля, задаваемого человеком для служебной учётки.
#:
#: Не «политика паролей» (её место в приложении), а защита от очевидной ошибки:
#: пустой или трёхсимвольный секрет означал бы открытую админку на публичном
#: домене. Значение ОДНО на `create_admin.py`, демо-сид и сид прогонов:
#: экспозиция у них совпадает (известный адрес на том же домене), а копия
#: числа разошлась бы молча. У сида прогонов рядом стоит СВОЯ мера для секрета
#: второго фактора (`MIN_TOTP_CHARS`, RFC 4226 §4): парольной меркой ключ не
#: меряют — двенадцать символов base32 дают 60 бит.
#: Ровно так уже расходилась проверка адреса базы, ради чего этот модуль и
#: появился.
MIN_PASSWORD_LENGTH = 12

#: Имена, которыми боевой compose зовёт свою базу.
COMPOSE_SERVICE_NAMES = frozenset({"postgres", "db"})


def refuse_foreign_database(
    database_url: str,
    *,
    allow_var: str,
    danger: str,
    command: str,
    allow_compose_names: bool = False,
) -> None:
    """Прервать работу, если строка подключения не похожа на локальную базу.

    `danger` — чем именно опасен ЭТОТ скрипт на чужой базе; попадает в каждый
    отказ, потому что человек на сервере читает не исходник, а сообщение.
    `allow_var` — имя переменной окружения с явным разрешением; значением
    задаётся САМ хост, а не «1»: подтверждение должно быть конкретным, иначе
    строка в профиле оболочки отключает защиту навсегда и для любой базы.

    `allow_compose_names` разрешает подтвердить имя службы боевого compose
    (`postgres`, `db`) — то есть открыть ИМЕННО боевую базу: признаки боевой
    строки её не отсеют, в ней их нет (`@postgres:5432/ketocare`), и после
    поимённого разрешения не остаётся ничего, кроме того, что человек набрал
    это слово сам. Для сида прогонов закрыто наглухо: на стенде он не нужен, а
    отказ называет хост — человек подставил бы его в переменную, и запрет
    вернулся бы через собственную подсказку. Демо-сид на стенде запускают по
    документу (docs/DEPLOY.md, «Демо-данные и фокус-группа»), и глухой запрет
    сломал бы законный путь, а не чужой — эта цена выбрана сознательно.
    """

    def _refuse(reason: str) -> NoReturn:
        raise SystemExit(
            f"{reason}\n"
            f"{danger}\n"
            f"Укажите локальную базу или передайте разрешение команде: "
            f"{allow_var}=<хост> {command}.\n"
            "Именно команде, а не строкой в файле окружения: скрипт читает\n"
            "окружение процесса, и постоянная запись отключала бы защиту навсегда."
        )

    try:
        url = make_url(database_url)
    except Exception:
        # Сюда прилетает что угодно: ArgumentError на мусоре, ValueError на
        # нечисловом порте. Голый traceback причину не объясняет.
        _refuse("Строку подключения не удалось разобрать.")

    # Подсказки ищутся в строке БЕЗ ПАРОЛЯ: пароль со слогом «prod» — совпадение,
    # а не признак боевой базы, и запрещать из-за него свою же базу незачем.
    lowered = url.render_as_string(hide_password=True).lower()
    hit = next((hint for hint in PRODUCTION_HINTS if hint in lowered), None)
    if hit is not None:
        # Первой и без права на разрешение: имя базы «ketocare_prod» на
        # локальном хосте — это туннель к бою, а не своя база.
        _refuse(f"В строке подключения есть «{hit}» — похоже на боевую базу.")

    # Параметр `host` доезжает до драйвера и решает, куда идёт соединение:
    # `@localhost/ketocare?host=чужой` выглядел бы локальным. Проверять надо то,
    # чем соединяются.
    #
    # Путь в этом параметре — unix-сокет, он локален по определению. Но значение
    # бывает СПИСКОМ через запятую — это отказоустойчивость asyncpg:
    # `host=/var/run,evil.com` разворачивается в `['/var/run', 'evil.com']`, и не
    # найдя сокета, драйвер идёт на второй адрес. Поэтому путём считается только
    # список, где КАЖДЫЙ элемент — путь.
    #
    # Ключ сравнивается точно: диалект различает регистр, `HOST=` он не
    # разбирает вовсе, а пробрасывает как лишний аргумент — вердикт «локально»
    # по такому ключу был бы неправдой.
    socket_path = False
    for key, value in url.query.items():
        if key != "host":
            if key.lower() == "host":
                _refuse(
                    f"Параметр «{key}» драйвер не разбирает как адрес — "
                    "используйте «host» или уберите его."
                )
            continue
        if not isinstance(value, str):
            # Кортеж — несколько параметров `host` разом, адрес неоднозначен.
            _refuse("В строке подключения есть параметр «host» — адрес подменяется.")
        parts = [part.strip() for part in value.split(",")]
        if all(part.startswith("/") for part in parts):
            socket_path = True
            continue
        _refuse("В строке подключения есть параметр «host» — адрес подменяется.")

    if socket_path:
        # Список портов имеет смысл только вместе со списком адресов, а
        # единственный признанный здесь случай — сокет (или их набор).
        ports = url.query.get("port")
        if isinstance(ports, str) and "," in ports:
            _refuse("В строке подключения список портов — адрес неоднозначен.")
        return

    # Завершающая точка в имени («postgres.») — тот же хост для DNS, но другая
    # строка для сравнения; пробелы вокруг значения переменной — обычная
    # опечатка. Нормализуются обе стороны.
    host = (url.host or "").strip().rstrip(".").lower()
    if host in LOCAL_HOSTS:
        return

    allowed = os.environ.get(allow_var, "").strip().rstrip(".").lower()
    if not allow_compose_names and host in COMPOSE_SERVICE_NAMES and allowed == host:
        _refuse(
            f"Хост «{host}» — имя базы в compose, и разрешением он не "
            "открывается: именно так объявлена боевая база."
        )

    if host != "" and allowed == host:
        return

    _refuse(f"Адрес базы не похож на локальный (хост «{host or 'не указан'}»).")
