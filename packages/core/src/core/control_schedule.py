"""График контрольных точек кетодиетотерапии (вопросы 17, 18 и 34; ADR-0050).

Чистые функции без I/O: их читают API (построение графика, карта пациента) и
воркер (напоминание семье перед визитом), и копия в каждом означала бы, что врач
и семья видят разный перечень анализов к одному и тому же визиту.

Все числа здесь — из ответов клиники от 09.09.2026, а не придуманы:

- визиты «через 1, 3, 6, 9 и 12 месяцев от старта диеты» — ответ на вопрос 17;
- «эффективность диеты определяется через 6 месяцев от начала… при
  эффективности пациент находится на ней минимум 2 года» — ответ на вопрос 18:
  отсюда пометка у шестимесячного визита и контрольная точка через 24 месяца;
- перечни анализов — ответ на вопросы 17 и 34, дословно: «еженедельно — ОАК,
  биохимия крови, глюкоза натощак, электролиты, бикарбонат; каждые 3–6 месяцев —
  ОАК, биохимия крови, липидный профиль, УЗИ почек, УЗИ печени, ЭКГ, рентген
  костей».

Что за клиникой осталось открытым, помечено `TODO(med)` у самого места.
"""

from __future__ import annotations

import calendar
import enum
from dataclasses import dataclass
from datetime import date


def add_months(day: date, months: int) -> date:
    """Та же дата через `months` календарных месяцев, прижатая к концу месяца.

    «Месяц от начала диеты» — календарный: с 15 марта до 15 апреля. Если такого
    числа в целевом месяце нет, берётся последний день: с 31 января — до 28
    февраля (29-го в високосный год). Считать «30 дней» значило бы подменить
    слово клиники своим числом.
    """

    month_index = day.month - 1 + months
    year = day.year + month_index // 12
    month = month_index % 12 + 1
    last_day = calendar.monthrange(year, month)[1]
    return date(year, month, min(day.day, last_day))


#: Месяцы контрольных визитов от начала терапии — ответ клиники на вопрос 17.
#:
#: TODO(med): вопрос 17 — уточняющий. В сводной таблице присланного документа
#: стоит другое расписание («первые 3 месяца после выписки каждые 3 недели»);
#: клинику переспросили 10.09.2026, ответа нет. Здесь — ряд из развёрнутого
#: ответа на сам вопрос; он же совпадает с консенсусом International Ketogenic
#: Diet Study Group (Kossoff et al., Epilepsia Open 2018).
VISIT_MONTHS: tuple[int, ...] = (1, 3, 6, 9, 12)

#: Когда оценивается эффективность и решается вопрос продолжения — ответ на
#: вопрос 18 («через 6 месяцев от начала»).
EFFICACY_REVIEW_MONTH = 6

#: Минимальный срок диеты при эффективности — ответ на вопрос 18 («минимум 2
#: года»). Контрольная точка ставится, чтобы решение о продолжении не было
#: пропущено; сама по себе она завершения не означает.
MIN_EFFECTIVE_COURSE_MONTH = 24

#: Все точки графика, которые строятся от даты начала терапии.
SCHEDULE_MONTHS: tuple[int, ...] = (*VISIT_MONTHS, MIN_EFFECTIVE_COURSE_MONTH)

#: «Еженедельно» — ответ клиники на вопросы 17 и 34, дословно.
#:
#: TODO(med): вопрос 34 — клиника не сказала, как долго идёт еженедельный
#: контроль (весь курс или первые недели после старта). Поэтому перечень
#: показывается врачу как есть и в напоминание семье перед визитом не идёт:
#: рассылать еженедельно то, чьего срока мы не знаем, значило бы выдумать срок.
WEEKLY_LABS: tuple[str, ...] = (
    "ОАК",
    "Биохимия крови",
    "Глюкоза натощак",
    "Электролиты",
    "Бикарбонат",
)

#: «Каждые 3–6 месяцев» — ответ клиники на вопросы 17 и 34, дословно.
PERIODIC_LABS: tuple[str, ...] = (
    "ОАК",
    "Биохимия крови",
    "Липидный профиль",
    "УЗИ почек",
    "УЗИ печени",
    "ЭКГ",
    "Рентген костей",
)

#: С какого месяца к визиту прикладывается перечень «каждые 3–6 месяцев».
#:
#: TODO(med): вопрос 34. «Каждые 3–6 месяцев» — интервал, а не срок; перечень
#: прикладывается к каждому визиту графика начиная с третьего месяца, то есть
#: по частой границе интервала. Реже — решение врача, и он видит перечень,
#: прежде чем звать семью.
PERIODIC_LABS_FROM_MONTH = 3


class ControlPurpose(enum.StrEnum):
    """Зачем назначена точка сверх обычного визита."""

    #: Оценка эффективности и решение о продолжении — 6 месяцев (вопрос 18).
    EFFICACY_REVIEW = "efficacy_review"
    #: Минимальный срок при эффективной диете пройден — 24 месяца (вопрос 18).
    CONTINUATION_REVIEW = "continuation_review"


@dataclass(frozen=True, slots=True)
class PlannedPoint:
    month_offset: int
    planned_on: date


def schedule_from(start: date) -> list[PlannedPoint]:
    """Точки графика от даты начала терапии."""

    return [PlannedPoint(month, add_months(start, month)) for month in SCHEDULE_MONTHS]


def labs_for(month_offset: int | None) -> tuple[str, ...]:
    """Перечень анализов к визиту.

    У визита вне графика (`month_offset is None`) перечня нет: к какому сроку
    терапии он относится, знает врач, а не расписание.
    """

    if month_offset is None or month_offset < PERIODIC_LABS_FROM_MONTH:
        return ()
    return PERIODIC_LABS


def purpose_for(month_offset: int | None) -> ControlPurpose | None:
    if month_offset == EFFICACY_REVIEW_MONTH:
        return ControlPurpose.EFFICACY_REVIEW
    if month_offset == MIN_EFFECTIVE_COURSE_MONTH:
        return ControlPurpose.CONTINUATION_REVIEW
    return None
