"""Имя статьи из её заголовка (ADR-0093).

Имя — то, чем помощник ссылается на источник (`[[kb:<имя>]]`), и то, что хранят
переписки семьи. Поэтому оно латиницей (адрес статьи и шаблон ссылки принимают
только `a-z0-9-`), выводится из заголовка один раз при создании и больше не
меняется — даже если заголовок потом поправят.
"""

from __future__ import annotations

import re

#: Транслитерация в духе ГОСТ 7.79-2000 (система Б) без диакритики, плюс
#: узбекская кириллица — заголовки бывают и на ней.
_TRANSLIT = {
    "а": "a",
    "б": "b",
    "в": "v",
    "г": "g",
    "д": "d",
    "е": "e",
    "ё": "yo",
    "ж": "zh",
    "з": "z",
    "и": "i",
    "й": "y",
    "к": "k",
    "л": "l",
    "м": "m",
    "н": "n",
    "о": "o",
    "п": "p",
    "р": "r",
    "с": "s",
    "т": "t",
    "у": "u",
    "ф": "f",
    "х": "kh",
    "ц": "ts",
    "ч": "ch",
    "ш": "sh",
    "щ": "shch",
    "ъ": "",
    "ы": "y",
    "ь": "",
    "э": "e",
    "ю": "yu",
    "я": "ya",
    "ў": "o",
    "қ": "q",
    "ғ": "g",
    "ҳ": "h",
}

#: Предел длины имени без суффикса: таблица держит 128, а суффикс «-NN» и
#: запас на него не должны упираться в край.
MAX_BASE_LENGTH = 80

_NOT_SLUG = re.compile(r"[^a-z0-9]+")


def slug_base(title: str) -> str:
    """Имя без суффикса: латиница, цифры и дефисы, без дефиса на краях."""

    latin = "".join(_TRANSLIT.get(char, char) for char in title.lower())
    slug = _NOT_SLUG.sub("-", latin).strip("-")
    if len(slug) > MAX_BASE_LENGTH:
        slug = slug[:MAX_BASE_LENGTH].rsplit("-", 1)[0] or slug[:MAX_BASE_LENGTH]
    return slug.strip("-") or "article"


def with_suffix(base: str, attempt: int) -> str:
    """Вариант имени: сначала само имя, потом `-2`, `-3` и так далее."""

    return base if attempt <= 1 else f"{base}-{attempt}"
